#!/usr/bin/env python3
"""Regression proof for finding F-1 (server group preference not honored
with a flat group list) and its remediation (tuple-syntax group list).

Runs three cases against the built OpenSSL 3.5.9 s_server / s_client and
asserts the negotiated group in each:

  R1  server groups "X25519MLKEM768/X25519" (tuple syntax: hybrid is the
      preferred tuple), client offers the hybrid but predicts ONLY a
      classical X25519 keyshare ("*X25519:X25519MLKEM768").
      EXPECT: server sends a HelloRetryRequest (first ServerHello is the
      88-byte HRR carrying the RFC 8446 HRR random and key_share 0x11ec),
      client retries with a hybrid keyshare, negotiated = X25519MLKEM768.

  R2  same client against a FLAT server list "X25519MLKEM768:X25519".
      EXPECT: no HRR, handshake completes with classical X25519
      ("Peer Temp Key: X25519") -- the silent downgrade F-1 describes.

  R3  tuple server, client predicts the hybrid keyshare.
      EXPECT: no HRR needed, negotiated = X25519MLKEM768.

Exit 0 only if all three expectations hold. Requires the built OpenSSL
3.5.9 in openssl-3.5.9-install/ and the test PKI in outputs/certs/
(generated by gen_certs.sh). Usage: python3 regression_hrr.py
"""
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
OPENSSL = os.path.join(HERE, "openssl-3.5.9-install", "bin", "openssl")
CERTS = os.path.join(HERE, "outputs", "certs")
PORT = 18443

ENV = dict(os.environ)
ENV["LD_LIBRARY_PATH"] = os.path.join(HERE, "openssl-3.5.9-install", "lib64")

HRR_RANDOM = "cf21ad74e59a6111be1d8c021e65b891c2a211167abb8c5e079e09e2c8a8339c"


def run_case(server_groups, client_groups):
    srv = subprocess.Popen(
        [OPENSSL, "s_server", "-accept", str(PORT),
         "-cert", os.path.join(CERTS, "server.crt"),
         "-key", os.path.join(CERTS, "server.key"),
         "-tls1_3", "-groups", server_groups,
         "-CAfile", os.path.join(CERTS, "ca.crt")],
        stdout=subprocess.DEVNULL, stderr=subprocess.STDOUT,
        stdin=subprocess.PIPE, env=ENV)
    try:
        time.sleep(1)
        p = subprocess.run(
            [OPENSSL, "s_client", "-connect", "127.0.0.1:%d" % PORT,
             "-tls1_3", "-groups", client_groups,
             "-CAfile", os.path.join(CERTS, "ca.crt"), "-brief", "-msg"],
            input=b"", capture_output=True, timeout=10, env=ENV)
        out = (p.stdout + p.stderr).decode("utf-8", "replace")
        flat = "".join(out.split())
        negotiated = None
        for line in out.splitlines():
            if "Negotiated TLS1.3 group:" in line:
                negotiated = line.split(":")[-1].strip()
        peer_temp = [l.strip() for l in out.splitlines()
                     if "Peer Temp Key:" in l]
        return p.returncode, negotiated, peer_temp, HRR_RANDOM in flat
    finally:
        srv.terminate()
        srv.wait(timeout=5)


def check(tag, got, want):
    ok = got == want
    print("%s: got=%r want=%r -> %s" % (tag, got, want, "PASS" if ok else "FAIL"))
    return ok


def main():
    ok = True
    # R1: tuple server + deferred hybrid keyshare -> HRR -> hybrid.
    rc, grp, _tmp, hrr = run_case("X25519MLKEM768/X25519",
                                  "*X25519:X25519MLKEM768")
    ok &= check("R1 rc", rc, 0)
    ok &= check("R1 negotiated group", grp, "X25519MLKEM768")
    ok &= check("R1 HRR seen", hrr, True)
    # R2: flat server + deferred hybrid keyshare -> silent classical fallback.
    rc, grp, tmp, hrr = run_case("X25519MLKEM768:X25519",
                                 "*X25519:X25519MLKEM768")
    ok &= check("R2 rc", rc, 0)
    ok &= check("R2 negotiated group (none: classical fallback)", grp, None)
    ok &= check("R2 Peer Temp Key is X25519", tmp,
                ["Peer Temp Key: X25519, 253 bits"])
    ok &= check("R2 HRR seen", hrr, False)
    # R3: tuple server + hybrid keyshare predicted -> hybrid, no HRR needed.
    rc, grp, _tmp, hrr = run_case("X25519MLKEM768/X25519",
                                  "*X25519MLKEM768:X25519")
    ok &= check("R3 rc", rc, 0)
    ok &= check("R3 negotiated group", grp, "X25519MLKEM768")
    print("ALL PASS" if ok else "FAILURES PRESENT")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
